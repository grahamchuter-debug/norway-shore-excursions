export function drawCtaButton(
  ctx: PdfContext,
  x: number,
  y: number,
  width: number,
  label: string,
  url: string,
  variant: "primary" | "navy" = "primary",
): number {
  const { pdf, config } = ctx;
  const height = 9;
  const fill = variant === "primary" ? config.colors.fjordBlue : config.colors.navyDeep;

  setFillRgb(pdf, fill);
  pdf.roundedRect(x, y, width, height, 2, 2, "F");

  pdfSetFont(ctx, "bold");
  pdf.setFontSize(8.5);
  setTextRgb(pdf, config.colors.white);
  const safeLabel = pdfSafeText(label, ctx.fonts);
  const textWidth = pdf.getTextWidth(safeLabel);
  pdf.text(safeLabel, x + (width - textWidth) / 2, y + 6);

  pdf.link(x, y, width, height, { url });

  return height;
}

export function drawSectionPanel(
  ctx: PdfContext,
  title: string,
  bodyLines: readonly string[],
): void {
  const { pdf, config, margin, contentWidth } = ctx;
  const pad = 4;
  const innerX = margin + pad;
  const innerWidth = contentWidth - pad * 2;
  const top = ctx.y;

  pdfSetFont(ctx, "normal");
  pdf.setFontSize(8);
  const wrappedLines = bodyLines.flatMap((line) =>
    pdf.splitTextToSize(line, innerWidth),
  );
  const boxHeight = 10 + wrappedLines.length * 3.6 + pad;

  ensureSpace(ctx, boxHeight + 4);

  setFillRgb(pdf, config.colors.cardBg);
  setDrawRgb(pdf, config.colors.border);
  pdf.setLineWidth(0.2);
  pdf.roundedRect(margin, top, contentWidth, boxHeight, 2, 2, "FD");

  pdfSetFont(ctx, "bold");
  pdf.setFontSize(9.5);
  setTextRgb(pdf, config.colors.navyDeep);
  pdf.text(title, innerX, top + 6);

  pdfSetFont(ctx, "normal");
  pdf.setFontSize(8);
  setTextRgb(pdf, config.colors.slate);

  let lineY = top + 11;
  for (const line of wrappedLines) {
    pdf.text(line, innerX, lineY);
    lineY += 3.6;
  }

  ctx.y = top + boxHeight + 4;
}

export function writeWrappedText(
  ctx: PdfContext,
  text: string,
  x: number,
  maxWidth: number,
  lineHeight: number,
  fontSize: number,
  color: Rgb,
  font: "normal" | "bold" = "normal",
): number {
  const { pdf } = ctx;
  pdfSetFont(ctx, font === "bold" ? "bold" : "normal");
  pdf.setFontSize(fontSize);
  setTextRgb(pdf, color);
  const lines = pdf.splitTextToSize(text, maxWidth);
  ensureSpace(ctx, lines.length * lineHeight);
  pdf.text(lines, x, ctx.y);
  const used = lines.length * lineHeight;
  ctx.y += used;
  return used;
}

export function shortenText(text: string, maxLength = 130): string {
  const trimmed = text.trim();
  if (trimmed.length <= maxLength) return trimmed;

  const sentence = trimmed.split(/(?<=[.!?])\s+/)[0]?.trim() ?? trimmed;
  if (sentence.length <= maxLength) return sentence;

  return `${trimmed.slice(0, maxLength - 3).trim()}...`;
}

export function resolvePortBookingUrl(
  rec: PortRecommendation,
  config: CruiseGuidePdfConfig,
): string {
  for (const pattern of config.tourBookingPatterns) {
    if (pattern.match.test(rec.recommended)) {
      return pattern.url;
    }
  }

  const portUrl = config.portBookingUrls[rec.portSlug];
  if (portUrl) return portUrl;

  return config.urls.defaultBooking;
}

export function buildVoyageSubtitle(
  cruiseLine: string,
  shipName: string,
  sailingMonth: string,
  sailingYear = "2026",
): string {
  const parts = [
    shipName.trim() || undefined,
    cruiseLine.trim() || undefined,
    sailingMonth.trim()
      ? `${sailingMonth.trim()} / ${sailingYear}`
      : sailingYear,
  ].filter(Boolean);

  return parts.join(" · ");
}

export function drawBulletList(
  ctx: PdfContext,
  x: number,
  maxWidth: number,
  bullets: readonly string[],
): number {
  const { pdf, config } = ctx;
  let used = 0;

  pdfSetFont(ctx, "normal");
  pdf.setFontSize(8);
  setTextRgb(pdf, config.colors.slate);

  for (const bullet of bullets) {
    ensureSpace(ctx, 4);
    const lines = pdf.splitTextToSize(`• ${bullet}`, maxWidth);
    pdf.text(lines, x, ctx.y);
    used += lines.length * 3.6;
    ctx.y += lines.length * 3.6;
  }

  return used;
}

