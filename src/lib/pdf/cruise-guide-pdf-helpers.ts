export function drawLabelValueLine(
  ctx: PdfContext,
  x: number,
  y: number,
  label: string,
  value: string,
  maxWidth: number,
  labelWidth = 28,
): void {
  const { pdf, config } = ctx;

  pdfSetFont(ctx, "bold");
  pdf.setFontSize(6.8);
  setTextRgb(pdf, config.colors.navyDeep);
  pdf.text(`${label}:`, x, y);

  pdfSetFont(ctx, "normal");
  setTextRgb(pdf, config.colors.slate);
  const valueLines = pdf.splitTextToSize(value, maxWidth - labelWidth);
  pdf.text(valueLines[0] ?? value, x + labelWidth, y);
}

