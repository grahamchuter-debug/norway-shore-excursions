export function drawShipSchedulePanel(
  ctx: PdfContext,
  x: number,
  y: number,
  width: number,
  input: ShipSchedulePanelInput,
): number {
  const { pdf, config } = ctx;
  const hasFitDetails =
    input.allAboardLabel &&
    input.portTimeLabel &&
    input.marginLabel &&
    input.confidenceLabel;
  const height = hasFitDetails ? 22 : 12;

  setFillRgb(pdf, config.colors.softGrey);
  setDrawRgb(pdf, config.colors.border);
  pdf.setLineWidth(0.15);
  pdf.roundedRect(x, y, width, height, 1.5, 1.5, "FD");

  pdfSetFont(ctx, "bold");
  pdf.setFontSize(6.5);
  setTextRgb(pdf, config.colors.navyDeep);
  pdf.text("Your Ship in Port", x + 3, y + 4);

  drawLabelValueLine(ctx, x + 3, y + 7.5, "Arrives", input.arrivalLabel, width / 2 - 6, 14);

  if (input.allAboardLabel) {
    drawLabelValueLine(
      ctx,
      x + width / 2,
      y + 7.5,
      "All Aboard",
      input.allAboardLabel,
      width / 2 - 6,
      18,
    );
  }

  if (hasFitDetails) {
    drawLabelValueLine(ctx, x + 3, y + 11, "Port Time", input.portTimeLabel!, width - 6, 16);

    pdfSetFont(ctx, "bold");
    pdf.setFontSize(6.5);
    setTextRgb(pdf, config.colors.navyDeep);
    pdf.text("Recommended Excursion", x + 3, y + 14.5);

    drawLabelValueLine(ctx, x + 3, y + 18, "Duration", input.durationLabel, width / 2 - 6, 16);
    drawLabelValueLine(
      ctx,
      x + width / 2,
      y + 18,
      "Return Margin",
      input.marginLabel!,
      width / 2 - 6,
      22,
    );
    drawLabelValueLine(
      ctx,
      x + 3,
      y + 21,
      "Confidence",
      input.confidenceLabel!,
      width - 6,
      18,
    );
  } else if (input.confirmAllAboardMessage) {
    pdfSetFont(ctx, "normal");
    pdf.setFontSize(6.3);
    setTextRgb(pdf, config.colors.slate);
    const lines = pdf.splitTextToSize(input.confirmAllAboardMessage, width - 6);
    pdf.text(lines.slice(0, 1), x + 3, y + 10.5);
  }

  return height;
}
